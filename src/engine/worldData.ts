export function getGradeBandForGrade(grade: GradeNumber): GradeBandId {
  if (grade <= 2) return 'grades-1-2';
  if (grade <= 5) return 'grades-3-5';
  if (grade <= 8) return 'grades-6-8';
  if (grade <= 10) return 'grades-9-10';
  return 'grades-11-12';
}

